import assert from 'node:assert/strict'
import { mkdirSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { createServer } from 'vite'
import { chromium } from 'playwright'
import { browserOptions } from './browserOptions.mjs'

const frontend = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const output = path.resolve(frontend, '../output/test-runs/workspace-t33-generation')
mkdirSync(output, { recursive: true })
const server = await createServer({ root: frontend, configFile: path.join(frontend, 'vite.config.js'),
  resolve: { alias: [{ find: /^vue$/, replacement: path.join(frontend, 'node_modules/vue/dist/vue.esm-bundler.js') }] },
  cacheDir: path.join(output, 'vite-cache'), optimizeDeps: { entries: ['tests/fixtures/workspaceLayout.html'] },
  server: { host: '127.0.0.1', port: 0, strictPort: false, open: false, proxy: {} } })
let browser
const errors = [], requests = [], stages = []
try {
  await server.listen()
  const origin = `http://127.0.0.1:${server.httpServer.address().port}`
  browser = await chromium.launch(browserOptions('TEST_BROWSER_CHANNEL'))
  const page = await browser.newPage({ viewport: { width: 1440, height: 960 } })
  const screenshot = name => page.screenshot({ path: path.join(output, name), animations: 'disabled' })
  page.on('pageerror', error => { errors.push(error.message); console.error(error.stack) })
  page.on('console', message => { if (message.type() === 'error') console.error(message.text()) })
  await page.route('**/*', route => {
    const url = new URL(route.request().url())
    if (url.origin !== origin || /^\/(api|health)(\/|$)/.test(url.pathname)) { requests.push(url.pathname); return route.abort() }
    return route.continue()
  })
  await page.goto(`${origin}/tests/fixtures/workspaceLayout.html`)
  await page.locator('.resource-panel-heading').waitFor({ timeout: 30000 })
  const center = async selector => page.locator(selector).evaluate(node => { const box = node.getBoundingClientRect(); return box.top + box.height / 2 })
  assert.ok(Math.abs(await center('.panel-heading-copy') - await center('.task-actions')) <= 2)
  await page.getByRole('button', { name: '刷新状态', exact: true }).click()
  assert.equal(await page.evaluate(() => window.layoutFixture.state.refreshes), 1)
  await page.getByRole('button', { name: '追加资源', exact: true }).click()
  await page.getByRole('menuitem', { name: '文本学习资源' }).click()
  assert.deepEqual(await page.evaluate(() => [...window.layoutFixture.state.appends]), ['text'])
  await page.evaluate(() => { window.layoutFixture.state.selectedJob.job_status = 'failed' })
  await page.getByRole('button', { name: '重新生成', exact: true }).click()
  assert.equal(await page.evaluate(() => window.layoutFixture.state.retries), 1)
  await page.evaluate(() => { window.layoutFixture.state.selectedJob.job_status = 'completed' })
  await page.getByRole('button', { name: '刷新资源', exact: true }).click()
  await screenshot('header-desktop.png')
  await page.setViewportSize({ width: 390, height: 844 })
  await page.waitForFunction(() => [...document.querySelectorAll('.el-popper')].every(el => getComputedStyle(el).display === 'none' || el.getBoundingClientRect().width === 0))
  await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))))
  await screenshot('header-mobile.png')
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), JSON.stringify(await page.locator('.generate-page, .resources-panel, .resource-panel-heading, .panel-heading-copy, .task-actions').evaluateAll(nodes => nodes.map(el => ({ class: el.className, width: el.getBoundingClientRect().width, right: el.getBoundingClientRect().right, scroll: el.scrollWidth })))) )
  await page.setViewportSize({ width: 1440, height: 960 })
  await page.evaluate(() => { window.layoutFixture.state.view = 'dialog'; window.layoutFixture.state.visible = true })
  await page.locator('.diagnosis-point-list li').first().waitFor()
  assert.equal(await page.locator('.diagnosis-point-list li').count(), 5)
  const originalEvidence = await page.evaluate(() => JSON.stringify(window.layoutFixture.snapshot.evidence))
  const originalResources = await page.evaluate(() => JSON.stringify(window.layoutFixture.snapshot.resource_versions))
  for (const node of ['diagnose', 'plan', 'retrieve', 'generate', 'review', 'claim_judge']) {
    await page.evaluate(node => { window.layoutFixture.state.node = node }, node)
    await page.waitForFunction(node => document.querySelector('.detail-content')?.dataset.contentKind === ({ diagnose:'diagnosis', plan:'path', retrieve:'evidence', generate:'document', review:'review', claim_judge:'claims' })[node], node)
    const box = await page.locator('.workflow-detail-dialog').evaluate(el => ({ width: el.clientWidth, scroll: el.scrollWidth, height: el.getBoundingClientRect().height, top: el.getBoundingClientRect().top }))
    assert.ok(box.scroll <= box.width + 1 && box.top + box.height <= 961, `${node} dialog must stay within viewport`)
    assert.equal(await page.locator('.audit-context').getAttribute('open'), null)
    if (node === 'retrieve') {
      assert.equal(await page.locator('.source-markdown table').count(), 1)
      assert.equal(await page.locator('.source-markdown h2').textContent(), '回答错误时的定位顺序')
      assert.equal(await page.locator('.source-markdown strong').textContent(), '证据条件')
      assert.equal(await page.locator('.source-markdown ul li').count(), 2)
      assert.equal(await page.locator('.source-markdown pre code').textContent(), 'print("example")')
      assert.equal(await page.locator('.source-markdown script, .source-markdown img, .source-markdown iframe').count(), 0)
      assert.equal(await page.evaluate(() => window.excerptExecuted), undefined)
      assert.equal(await page.getByText('冻结证据缺失，未使用其他来源替代。', { exact: true }).count(), 1)
      assert.equal(await page.locator('.source-raw').getAttribute('open'), null)
      const cellBorders = await page.locator('.source-markdown th, .source-markdown td').evaluateAll(cells => cells.every(cell => ['Top', 'Right', 'Bottom', 'Left'].every(side => parseFloat(getComputedStyle(cell)[`border${side}Width`]) >= 1 && getComputedStyle(cell)[`border${side}Style`] === 'solid')))
      assert.ok(cellBorders)
      await page.getByText('查看原始 Markdown', { exact: true }).click()
      assert.equal(await page.locator('.source-raw pre').textContent(), await page.evaluate(() => window.layoutFixture.snapshot.evidence[0].excerpt))
      await page.getByText('查看原始 Markdown', { exact: true }).click()
    }
    if (node === 'generate') {
      assert.equal(await page.locator('.generated-markdown h1').textContent(), '讲义 · RAG 基础')
      assert.equal(await page.locator('.generated-markdown table').count(), 1)
      assert.equal(await page.locator('.generated-markdown ul li').count(), 2)
      assert.equal(await page.locator('.generated-markdown pre code').textContent(), 'print("RAG")')
      assert.equal(await page.locator('.generated-markdown script, .generated-markdown img, .generated-markdown iframe').count(), 0)
      assert.equal(await page.evaluate(() => window.generatedExecuted), undefined)
      assert.equal(await page.locator('.generated-raw').getAttribute('open'), null)
      const cellBorders = await page.locator('.generated-markdown th, .generated-markdown td').evaluateAll(cells => cells.every(cell => ['Top','Right','Bottom','Left'].every(side => parseFloat(getComputedStyle(cell)[`border${side}Width`]) >= 1 && getComputedStyle(cell)[`border${side}Style`] === 'solid')))
      assert.ok(cellBorders)
      await page.locator('.generated-raw summary').click()
      assert.equal(await page.locator('.generated-raw pre').textContent(), await page.evaluate(() => window.layoutFixture.snapshot.resource_versions[0].content_text))
      await page.locator('.generated-raw summary').click()
      await page.getByRole('combobox', { name:'审核资源' }).selectOption('r2')
      assert.equal(await page.locator('.generated-markdown h1').textContent(), '第二份资源')
      await page.getByRole('combobox', { name:'审核资源' }).selectOption('r1')
      assert.equal(await page.locator('.generated-markdown h1').textContent(), '讲义 · RAG 基础')
    }
    await page.locator('.el-dialog__body').evaluate(el => { el.scrollTop = 0 })
    await screenshot(`${node}-desktop.png`)
    stages.push(node)
  }
  await page.setViewportSize({ width: 390, height: 844 })
  await page.evaluate(() => { window.layoutFixture.state.node = 'diagnose' })
  await page.locator('.diagnosis-point-list').waitFor()
  assert.ok(await page.locator('.el-dialog__body').evaluate(el => el.scrollWidth <= el.clientWidth + 1))
  await screenshot('diagnosis-mobile.png')
  await page.evaluate(() => { window.layoutFixture.state.node = 'retrieve' })
  await page.locator('.source-markdown table').waitFor()
  const tableLayout = await page.locator('.source-markdown .markdown-table-scroll').evaluate(el => ({ width: el.clientWidth, content: el.scrollWidth, overflow: getComputedStyle(el).overflowX }))
  assert.ok(tableLayout.content > tableLayout.width && tableLayout.overflow === 'auto')
  assert.ok(await page.locator('.el-dialog__body').evaluate(el => el.scrollWidth <= el.clientWidth + 1))
  await screenshot('retrieval-mobile.png')
  assert.equal(await page.evaluate(() => JSON.stringify(window.layoutFixture.snapshot.evidence)), originalEvidence)
  await page.evaluate(() => { window.layoutFixture.state.node = 'generate' })
  await page.locator('.generated-markdown table').waitFor()
  const generatedTableLayout = await page.locator('.generated-markdown .markdown-table-scroll').evaluate(el => ({ width:el.clientWidth, content:el.scrollWidth, overflow:getComputedStyle(el).overflowX }))
  assert.ok(generatedTableLayout.content > generatedTableLayout.width && generatedTableLayout.overflow === 'auto')
  assert.ok(await page.locator('.el-dialog__body').evaluate(el => el.scrollWidth <= el.clientWidth + 1))
  assert.equal(await page.evaluate(() => JSON.stringify(window.layoutFixture.snapshot.resource_versions)), originalResources)
  await screenshot('generation-mobile.png')
  await page.setViewportSize({ width: 1440, height: 960 })
  await page.evaluate(() => { window.layoutFixture.state.visible = false; window.layoutFixture.state.view = 'onboarding' })
  await page.locator('.workflow-detail-dialog').waitFor({ state: 'hidden' })
  await page.locator('.progress-panel').waitFor()
  const alignment = () => page.evaluate(() => {
    const left = document.querySelector('.progress-panel').getBoundingClientRect(), right = document.querySelector('.work-card').getBoundingClientRect()
    return { top: Math.abs(left.top - right.top), bottom: Math.abs(left.bottom - right.bottom) }
  })
  const before = await alignment()
  assert.ok(before.top <= 1 && before.bottom <= 1, JSON.stringify(before))
  await screenshot('onboarding-desktop.png')
  await page.locator('.fixture-scroll').evaluate(el => { el.scrollTop = 250 })
  const after = await alignment()
  assert.ok(after.top <= 1 && after.bottom <= 1, JSON.stringify(after))
  await page.setViewportSize({ width: 390, height: 844 })
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1))
  await screenshot('onboarding-mobile.png')
  assert.deepEqual(errors, [])
  assert.deepEqual(requests, [])
  writeFileSync(path.join(output, 'browser.json'), JSON.stringify({ status: 'passed', scope: 'isolated presentation, not full business flow or fit measurement', stages, before, after, markdown: { semanticPreview: true, rawPreserved: true, safeHtml: true, missingEvidence: true, tableLayout }, generatedMarkdown: { preview:true, rawPreserved:true, resourceSelection:true, safeHtml:true, generatedTableLayout }, errors, requests }, null, 2))
  console.log('PASS header actions, six stage layouts, Markdown evidence/raw/safety, mobile overflow and onboarding alignment; no API calls')
} finally { await browser?.close(); await server.close() }
