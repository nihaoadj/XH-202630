"""Export selected public Pydantic contracts, without constructing the application.

The declarations describe JSON structure. Python continues to own field/business
validation; client guards only validate the explicitly selected boundary fields.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from app.models.courseware.contracts import (
    CoursewareBatchCreateRequest, CoursewareBatchJobResponse, CoursewareJobCreateRequest,
    CoursewareJobDetail, CoursewareJobListResponse, CoursewareJobResponse,
)
from app.models.courseware.events import CoursewareLearningEvent, CoursewareLearningEventAck, CoursewareLearningEventBatch
from app.models.learning_documents.schemas import (
    ContinueResourceBatchRequest, GenerateRequest, GenerationJobCreateResponse,
    GenerationJobListResponse, GenerationJobStatusResponse,
)
from app.models.reports.contracts import CurrentReportResponse, ReportInvalidation, ReportResponse, ReportWindow
from app.models.shared.persistence import RunStatus, RunSummary, RunTimeline, WorkflowEventType
from app.models.shared.streaming import PublicRunEvent, PublicRunSnapshot

MODELS = (
    CoursewareBatchCreateRequest, CoursewareBatchJobResponse, CoursewareJobCreateRequest,
    CoursewareJobDetail, CoursewareJobListResponse, CoursewareJobResponse,
    CoursewareLearningEvent, CoursewareLearningEventAck, CoursewareLearningEventBatch,
    ContinueResourceBatchRequest, GenerateRequest, GenerationJobCreateResponse,
    GenerationJobListResponse, GenerationJobStatusResponse, CurrentReportResponse,
    ReportInvalidation, ReportResponse, ReportWindow, RunSummary, RunTimeline,
    PublicRunEvent, PublicRunSnapshot,
)
OUTPUT = ROOT / "frontend/src/contracts/generated"
ANNOTATIONS = {"title", "description", "default", "format", "minLength", "maxLength", "pattern",
               "minimum", "maximum", "exclusiveMinimum", "exclusiveMaximum", "minItems", "maxItems"}
STRUCTURE = {"$defs", "$ref", "type", "properties", "required", "additionalProperties", "items", "anyOf", "allOf", "oneOf", "enum", "const"}


def literal(value):
    return json.dumps(value, ensure_ascii=False)


def typescript(schema):
    unsupported = set(schema) - ANNOTATIONS - STRUCTURE
    if unsupported:
        raise ValueError(f"unsupported schema keywords: {sorted(unsupported)}")
    if "$ref" in schema:
        ref = schema["$ref"]
        if not ref.startswith("#/$defs/"):
            raise ValueError("only local Pydantic references are supported")
        return ref.removeprefix("#/$defs/")
    if "const" in schema:
        return literal(schema["const"])
    if "enum" in schema:
        return " | ".join(map(literal, schema["enum"]))
    for name, separator in (("anyOf", " | "), ("oneOf", " | "), ("allOf", " & ")):
        if name in schema:
            return separator.join(f"({typescript(child)})" for child in schema[name])
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{typescript(schema.get('items', {}))}>"
    if kind == "object":
        required = set(schema.get("required", []))
        fields = [f"  {literal(key)}{'' if key in required else '?'}: {typescript(value)};"
                  for key, value in sorted(schema.get("properties", {}).items())]
        additional = schema.get("additionalProperties")
        if additional is True or isinstance(additional, dict):
            # unknown admits named fields too, without laundering them into any.
            extra = typescript(additional) if isinstance(additional, dict) and not fields else "unknown"
            fields.append(f"  [key: string]: {extra};")
        return "{\n" + "\n".join(fields) + "\n}" if fields else "Record<string, unknown>"
    if kind in {"integer", "number"}:
        return "number"
    if kind in {"string", "boolean", "null"}:
        return kind
    if kind is None:
        return "unknown"
    raise ValueError(f"unsupported JSON type: {kind}")


def build_outputs():
    definitions = {}
    roots = {}
    for model in MODELS:
        schema = model.model_json_schema(mode="validation")
        nested = schema.pop("$defs", {})
        for name, definition in {**nested, model.__name__: schema}.items():
            if name in definitions and definitions[name] != definition:
                raise ValueError(f"conflicting contract definition: {name}")
            definitions[name] = definition
        roots[model.__name__] = {"$ref": f"#/$defs/{model.__name__}"}
    definitions["RunStatus"] = {"enum": [item.value for item in RunStatus]}
    header = "// Generated by scripts/export_frontend_contracts.py; do not edit.\n"
    declarations = header + "\n".join(f"export type {name} = {typescript(schema)};\n" for name, schema in sorted(definitions.items()))
    declarations += 'export type GenerationJobStatus = GenerationJobStatusResponse["job_status"];\n'
    declarations += 'export type CoursewareJobState = CoursewareJobResponse["status"];\n'
    declarations += 'export type ReportWindowDays = ReportWindow["window_days"];\n'
    # Only constants consumed at runtime are emitted, not the full schema graph.
    values = {
        "JOB_STATUSES": GenerationJobStatusResponse.model_json_schema()["properties"]["job_status"]["enum"],
        "RUN_STATUSES": [item.value for item in RunStatus],
        "WORKFLOW_EVENT_TYPES": [item.value for item in WorkflowEventType],
        "REPORT_WINDOW_DAYS": ReportWindow.model_json_schema()["properties"]["window_days"]["enum"],
        "REPORT_REVISION_PATTERN": CurrentReportResponse.model_json_schema()["properties"]["report_revision"]["pattern"],
    }
    constants = header + "\n".join(f"export const {key} = Object.freeze({literal(value)})" for key, value in values.items()) + "\n"
    manifest = {"contract_schema_version": "1.0", "roots": roots, "$defs": dict(sorted(definitions.items()))}
    return {"contracts.d.ts": declarations, "constants.js": constants,
            "schema.json": json.dumps(manifest, ensure_ascii=False, sort_keys=True, indent=2) + "\n"}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args()
    outputs = build_outputs()
    mismatches = [name for name, value in outputs.items()
                  if not (args.output / name).exists() or (args.output / name).read_bytes() != value.encode("utf-8")]
    if args.check:
        for name in mismatches:
            print(f"CONTRACT_DRIFT: {name}; run python scripts/export_frontend_contracts.py")
        if not mismatches:
            print(f"Frontend contracts match {len(MODELS)} public models")
        return int(bool(mismatches))
    args.output.mkdir(parents=True, exist_ok=True)
    for name, value in outputs.items():
        (args.output / name).write_bytes(value.encode("utf-8"))
    print(f"Exported {len(MODELS)} public models to {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
